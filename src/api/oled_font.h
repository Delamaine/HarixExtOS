// Pure text layer for the SSD1306 128x64 OLED: packs one line of text into
// 21 glyph slots (5 columns + 1 blank gap each). No Arduino dependency, so it
// unit-tests natively. The table is the classic fixed-space 5x7 ASCII font,
// chars 0x20..0x7E (heritage: Adafruit GFX glcdfont.c, public domain).
// Stored as plain const: readable natively and on-device (475 B of ESP8266
// RAM; flash it with PROGMEM if that ever matters).

