// Column byte of a glyph pointer (single place to add PROGMEM if ever needed).
inline uint8_t oledGlyphByte(const uint8_t* glyph, int i) { return glyph[i]; }

// Pack `text` into 21 slots of [5 glyph columns + 1 blank]; longer text is
// truncated, the rest of the line padded with blanks.
inline void oledPackLine(const char* text, uint8_t out[OLED_LINE_BYTES]) {
  for (int slot = 0; slot < OLED_LINE_CHARS; ++slot) {
    uint8_t* dst = out + slot * 6;
    char ch = '\0';
    if (text != nullptr && *text != '\0') ch = *text++;
    if (ch == '\0') {
      memset(dst, 0, 6);
      continue;
    }
    const uint8_t* g = oledGlyph(ch);
    dst[0] = g[0];
    dst[1] = g[1];
    dst[2] = g[2];
    dst[3] = g[3];
    dst[4] = g[4];
    dst[5] = 0;
  }
}

